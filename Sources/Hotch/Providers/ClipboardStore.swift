import AppKit

// MARK: - Model

/// One remembered clipboard entry. Text only, deliberately: files, images and
/// rich content each raise their own privacy and rendering questions, and the
/// glanceable version of this feature is "what were those last few strings".
struct ClipboardItem: Sendable, Hashable, Identifiable {
    var id: Int
    /// The full string, so copying it back returns exactly what was copied.
    var text: String
    /// One line for the row, cut server-side rather than trusting lineLimit
    /// with a 2MB string.
    var preview: String
    var copiedAt: Date
}

// MARK: - Store

/// The last few text clipboards, held in memory and nowhere else.
///
/// The pasteboard has no notification API, so everyone polls `changeCount` —
/// one integer read a second, costing nothing. What matters here is what is
/// *not* kept:
///
/// - **Nothing is written to disk.** Quitting forgets the history. A clipboard
///   log that survives reboots is a different, heavier feature with real
///   custody questions; five recent strings in RAM is a convenience.
/// - **Concealed and transient pasteboards are skipped.** Password managers
///   mark their writes with `org.nspasteboard.ConcealedType` (and auto-type
///   uses `TransientType`); honouring those marks is the difference between a
///   clipboard history and a keylogger.
/// - **Huge strings are truncated** at a size that keeps "copied a whole log
///   file" from bloating the app, while still round-tripping anything a person
///   would recognisably paste.
@MainActor
final class ClipboardStore: ObservableObject {
    nonisolated static let maxItems = 5
    /// Beyond this a string is stored cut. Large enough that losing the tail
    /// only matters for content nobody scans by eye anyway.
    nonisolated static let maxStoredLength = 20_000
    nonisolated static let previewLength = 120

    /// Pasteboard types whose presence means "do not record this write".
    nonisolated static let skipMarkers: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    @Published var items: [ClipboardItem] = []
    @Published var enabled: Bool = true {
        didSet {
            if !enabled { items = [] }
        }
    }

    private var timer: Timer?
    private var lastChangeCount: Int = NSPasteboard.general.changeCount
    private var nextID = 0

    func start() {
        stop()
        let timer = Timer(timeInterval: 1.0, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated {
                self?.tick()
            }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Re-copies an item, from the popover's rows. The pasteboard write bumps
    /// `changeCount`, so the next tick would re-record it; moving it to the top
    /// of the list first makes that a no-op instead of a duplicate.
    func copyBack(_ item: ClipboardItem) {
        if let index = items.firstIndex(of: item) {
            items.remove(at: index)
            items.insert(item, at: 0)
        }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    private func tick() {
        guard enabled else { return }
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        // The marks come first: a concealed write must not even be read.
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: ClipboardStore.skipMarkers) else { return }

        guard var text = pasteboard.string(forType: .string) else { return }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        if text.count > ClipboardStore.maxStoredLength {
            text = String(text.prefix(ClipboardStore.maxStoredLength))
        }

        // Copying the same thing twice moves it to the top rather than
        // filling the short list with one string.
        if let existing = items.firstIndex(where: { $0.text == text }) {
            var item = items.remove(at: existing)
            item.copiedAt = Date()
            items.insert(item, at: 0)
            return
        }

        nextID += 1
        let item = ClipboardItem(id: nextID,
                                 text: text,
                                 preview: ClipboardStore.preview(of: trimmed),
                                 copiedAt: Date())
        items.insert(item, at: 0)
        if items.count > ClipboardStore.maxItems {
            items.removeLast(items.count - ClipboardStore.maxItems)
        }
    }

    /// First line, cut to length, whitespace collapsed — a row, not a document.
    nonisolated static func preview(of text: String) -> String {
        let firstLine = text.split(separator: "\n", maxSplits: 1,
                                   omittingEmptySubsequences: true).first.map(String.init) ?? text
        let collapsed = firstLine.split(separator: " ", omittingEmptySubsequences: true)
            .joined(separator: " ")
        if collapsed.count <= previewLength { return collapsed }
        return String(collapsed.prefix(previewLength)) + "\u{2026}"
    }
}
