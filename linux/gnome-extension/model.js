// Pure state shared by the GNOME views and fixture tests.
export const HOMES = [
    ['panel', 'Top bar'], ['pill', 'Floating pill'], ['orb', 'Orb'],
    ['edge-left', 'Left edge'], ['edge-right', 'Right edge'], ['edge-bottom', 'Bottom edge'],
];
export const DEFAULTS = {home: 'panel', theme: 'system', displayMode: 'used',
    refreshSeconds: 60, providers: ['claude', 'codex'], clipboardEnabled: false};

export function normalizeSettings(raw = {}) {
    const result = {...DEFAULTS, providers: [...DEFAULTS.providers]};
    if (!raw || typeof raw !== 'object') raw = {};
    if (HOMES.some(([id]) => id === raw.home)) result.home = raw.home;
    if (['system', 'light', 'dark'].includes(raw.theme)) result.theme = raw.theme;
    if (['used', 'remaining'].includes(raw.displayMode)) result.displayMode = raw.displayMode;
    if ([30, 60, 120, 300].includes(raw.refreshSeconds)) result.refreshSeconds = raw.refreshSeconds;
    if (Array.isArray(raw.providers) && raw.providers.every(p => ['claude', 'codex'].includes(p)))
        result.providers = [...new Set(raw.providers)];
    if (typeof raw.clipboardEnabled === 'boolean') result.clipboardEnabled = raw.clipboardEnabled;
    for (const key of ['pillX', 'pillY'])
        if (Number.isFinite(raw[key])) result[key] = raw[key];
    result.focus = normalizeFocus(raw.focus);
    return result;
}

export function displayedPercent(used, mode) {
    const value = Math.max(0, Math.min(100, used));
    return mode === 'remaining' ? 100 - value : value;
}

export function normalizeFocus(raw = {}) {
    if (!raw || typeof raw !== 'object') raw = {};
    return {
        mode: raw.mode === 'stopwatch' ? 'stopwatch' : 'timer',
        duration: Number.isFinite(raw.duration) ? Math.max(60, Math.min(86400, raw.duration)) : 1500,
        elapsed: Number.isFinite(raw.elapsed) ? Math.max(0, raw.elapsed) : 0,
        startedAt: Number.isFinite(raw.startedAt) && raw.startedAt > 0 ? raw.startedAt : null,
        title: typeof raw.title === 'string' ? raw.title.slice(0, 120) : '',
    };
}

export function focusReading(focus, now) {
    const elapsed = focus.elapsed + (focus.startedAt === null ? 0 : Math.max(0, now - focus.startedAt));
    const done = focus.mode === 'timer' && elapsed >= focus.duration;
    return {elapsed, done, seconds: focus.mode === 'timer' ? Math.max(0, focus.duration - elapsed) : elapsed};
}

export function focusAction(state, action, now) {
    const f = normalizeFocus(state);
    const reading = focusReading(f, now);
    if (action === 'reset') return {...f, elapsed: 0, startedAt: null};
    if (action === 'pause' || action === 'complete')
        return {...f, elapsed: f.mode === 'timer' ? Math.min(reading.elapsed, f.duration) : reading.elapsed, startedAt: null};
    if (action === 'start') return {...f, elapsed: reading.done ? 0 : reading.elapsed, startedAt: now};
    return f;
}

export function clockText(seconds) {
    const s = Math.max(0, Math.ceil(seconds));
    const h = Math.floor(s / 3600);
    return `${h ? `${h}:` : ''}${String(Math.floor(s / 60) % 60).padStart(2, '0')}:${String(s % 60).padStart(2, '0')}`;
}

export function privateClipboard(types) {
    return (types ?? []).some(t => /password|keepass|concealed|transient|autogenerated/i.test(t));
}

export function rememberClipboard(items, text) {
    if (typeof text !== 'string' || !text.trim()) return items;
    const clipped = text.slice(0, 20000);
    return [clipped, ...items.filter(item => item !== clipped)].slice(0, 5);
}

export function companionPosition(home, monitor, width, height, x, y, panelHeight) {
    if (home === 'edge-left') { x = monitor.x; y = monitor.y + (monitor.height - height) / 2; }
    if (home === 'edge-right') { x = monitor.x + monitor.width - width; y = monitor.y + (monitor.height - height) / 2; }
    if (home === 'edge-bottom') { x = monitor.x + (monitor.width - width) / 2; y = monitor.y + monitor.height - height; }
    return [Math.round(Math.max(monitor.x, Math.min(x, monitor.x + monitor.width - width))),
        Math.round(Math.max(monitor.y + panelHeight, Math.min(y, monitor.y + monitor.height - height)))];
}
